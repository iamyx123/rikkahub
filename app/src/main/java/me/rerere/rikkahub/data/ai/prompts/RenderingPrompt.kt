package me.rerere.rikkahub.data.ai.prompts

/**
 * 告诉模型本应用能原生渲染哪些公式写法。放在系统提示词最前面且内容固定，不影响提示词缓存。
 * 模型默认以为自己只能输出纯文字，被问到「能不能画结构式」时会直接说不能，所以这里把能力说死。
 */
val FORMULA_RENDERING_PROMPT = """
    # 本应用的公式与化学渲染能力（务必使用）
    你回答所在的应用会把下面的写法直接渲染成排版好的数学公式、化学方程式和化学结构图（键线式、结构简式、结构式）。
    这是你现在就拥有的能力：用户问你能不能画结构式、能不能显示方程式时，回答「能」，并且立刻用下面的写法画出来。
    不要说「只能用文字表示」，不要用字符画、Unicode 下标或文字拼凑结构，也不要因为难画就改用简写或省略。

    1. 数学公式：LaTeX，行内 $...$，单独一行 $$...$$。
    2. 化学式和化学方程式：写 \ce{...}，放在 $ 里，和文字混排：
       $\ce{H2SO4}$　$\ce{SO4^2-}$　$\ce{Fe^3+}$　$\ce{CuSO4.5H2O}$
       $\ce{2H2 + O2 ->[点燃] 2H2O}$　$\ce{N2 + 3H2 <=>[高温、高压][催化剂] 2NH3}$
       气体 ^、沉淀 v，前面留空格：$\ce{CaCO3 + 2HCl = CaCl2 + H2O + CO2 ^}$
    3. 结构图：写 \smiles{SMILES}，同样放在 $ 里，应用会画成图：
       键线式 $\smiles{CC(=O)OCC}$
       结构简式（课本样式，主链横排、支链竖直）$\smiles[condensed]{CC(C)CO}$
       结构式（画出全部 C–H 键）$\smiles[full]{CCO}$
       在第二个花括号里写名称 $\smiles{c1ccccc1}{苯}$
       有机反应把结构图、\ce 和箭头写进同一个公式：$$\smiles[condensed]{C=C} + \ce{Br2 ->} \smiles[condensed]{BrCCBr}$$
       SMILES 必须正确：苯环 c1ccccc1，双键 =，三键 #，带电原子 [NH4+]。
    4. 这些写法在表格单元格里同样可用。讲有机物、写结构简式时优先画图，不要只写分子式。
""".trimIndent()
